#!/usr/bin/env python3
"""Offline PostgreSQL benchmark of existing vs compact LifeDashPro GTFS layouts.

DESTRUCTIVE ONLY to an isolated, disposable local PostgreSQL database.
No Supabase credentials, no Supabase host, no source-table changes in production.
The compact design is a prototype and is NOT a production migration.
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import statistics
import time
from pathlib import Path
from urllib.parse import urlparse

import psycopg

EXPECTED_DB = "ldp_gtfs_scratch"
EXPECTED_USER = "ldp_gtfs_scratch"
MAX_STOP_TIMES = 2_500_000

RAW_DDL = """
create schema legacy_bench;
create table legacy_bench.stops(
    feed_source text not null, stop_id text not null, stop_name text,
    stop_code text, parent_station text, platform_code text,
    stop_lat double precision, stop_lon double precision);
create table legacy_bench.trips(
    feed_source text not null, trip_id text not null, route_id text,
    service_id text, trip_headsign text, trip_short_name text,
    direction_id integer, shape_id text);
create table legacy_bench.stop_times(
    feed_source text not null, trip_id text not null, stop_sequence integer not null,
    stop_id text not null, arrival_time text, departure_time text,
    arrival_secs integer, departure_secs integer, stop_headsign text,
    pickup_type integer, drop_off_type integer);
"""

COMPACT_DDL = """
create schema compact_bench;
create table compact_bench.stops(
    stop_key integer generated by default as identity primary key,
    feed_source text not null, stop_id text not null, stop_name text,
    stop_code text, parent_station text, platform_code text,
    stop_lat double precision, stop_lon double precision,
    unique(feed_source, stop_id));
create table compact_bench.trips(
    trip_key integer generated by default as identity primary key,
    feed_source text not null, trip_id text not null, route_id text,
    service_id text, trip_headsign text, trip_short_name text,
    direction_id integer, shape_id text,
    unique(feed_source, trip_id));
create table compact_bench.stop_times(
    trip_key integer not null references compact_bench.trips(trip_key),
    stop_sequence integer not null,
    stop_key integer not null references compact_bench.stops(stop_key),
    arrival_secs integer, departure_secs integer,
    stop_headsign text, pickup_type smallint, drop_off_type smallint);
"""

IMPORT_FILES = {
    "stops": ("stops.csv", "feed_source,stop_id,stop_name,stop_code,parent_station,platform_code,stop_lat,stop_lon"),
    "trips": ("trips.csv", "feed_source,trip_id,route_id,service_id,trip_headsign,trip_short_name,direction_id,shape_id"),
    "stop_times": ("stop_times.csv", "feed_source,trip_id,stop_sequence,stop_id,arrival_time,departure_time,arrival_secs,departure_secs,stop_headsign,pickup_type,drop_off_type")
}

def validate_local_url(dsn: str) -> None:
    p = urlparse(dsn)
    if p.scheme not in ("postgresql", "postgres"):
        raise RuntimeError("Benchmark requires a local PostgreSQL URL")
    if p.hostname not in ("127.0.0.1", "localhost", "::1"):
        raise RuntimeError("Safety stop: benchmark REFUSES remote databases")
    if p.port != 5432 or p.path != "/" + EXPECTED_DB or p.username != EXPECTED_USER:
        raise RuntimeError("Safety stop: database name/user/port must match disposable benchmark instance")

def copy_csv(cur, name: str, path: Path, cols: str) -> None:
    with cur.copy("COPY legacy_bench." + name + " (" + cols +
                  ") FROM STDIN WITH (FORMAT csv, HEADER true)") as writer:
        with path.open("rb") as f:
            while True:
                chunk = f.read(1024 * 1024)
                if not chunk:
                    break
                writer.write(chunk)

def size_breakdown(cur, schema: str) -> dict:
    result = {}
    for name in ("stops", "trips", "stop_times"):
        cur.execute("""
            select pg_relation_size(%s::regclass), pg_indexes_size(%s::regclass),
                   pg_total_relation_size(%s::regclass)
        """, (schema + "." + name,) * 3)
        heap, indexes, total = cur.fetchone()
        result[name] = {"heap_mb": round(heap/1048576, 2),
                        "index_mb": round(indexes/1048576, 2),
                        "total_mb": round(total/1048576, 2)}
    result["total_mb"] = round(sum(result[n]["total_mb"] for n in ("stops","trips","stop_times")), 2)
    return result

def timed(cur, statement: str, params: tuple, repeats: int = 6):
    durations, output = [], None
    for _ in range(repeats):
        t = time.perf_counter()
        cur.execute(statement, params)
        current = cur.fetchall()
        durations.append((time.perf_counter()-t)*1000)
        if output is None:
            output = current
        elif output != current:
            raise RuntimeError("Non-deterministic query results during benchmark")
    return output, round(statistics.median(durations), 2)

RAW_DEPS = """
    select st.trip_id, st.departure_secs, st.stop_sequence
    from legacy_bench.stop_times st
    where st.feed_source='de-national' and st.stop_id=%s
      and st.departure_secs between %s and %s
    order by st.departure_secs, st.trip_id, st.stop_sequence limit 50
"""
COMPACT_DEPS = """
    select tm.trip_id, st.departure_secs, st.stop_sequence
    from compact_bench.stops sm
    join compact_bench.stop_times st on st.stop_key=sm.stop_key
    join compact_bench.trips tm on tm.trip_key=st.trip_key
    where sm.feed_source='de-national' and sm.stop_id=%s
      and st.departure_secs between %s and %s
    order by st.departure_secs, tm.trip_id, st.stop_sequence limit 50
"""
RAW_ROUTE = """
    select stop_id, stop_sequence, arrival_secs, departure_secs,
           coalesce(stop_headsign,''),pickup_type,drop_off_type
    from legacy_bench.stop_times
    where feed_source='de-national' and trip_id=%s
    order by stop_sequence
"""
COMPACT_ROUTE = """
    select sm.stop_id, st.stop_sequence, st.arrival_secs, st.departure_secs,
           coalesce(st.stop_headsign,''),st.pickup_type::integer,st.drop_off_type::integer
    from compact_bench.trips tm
    join compact_bench.stop_times st on st.trip_key=tm.trip_key
    join compact_bench.stops sm on sm.stop_key=st.stop_key
    where tm.feed_source='de-national' and tm.trip_id=%s
    order by st.stop_sequence
"""

def main() -> int:
    ap=argparse.ArgumentParser()
    ap.add_argument("--dir",type=Path,required=True)
    ap.add_argument("--db-url",required=True)
    ap.add_argument("--report",type=Path,default=None)
    args=ap.parse_args()
    validate_local_url(args.db_url)

    manifest=json.loads((args.dir/"manifest.json").read_text(encoding="utf-8"))
    if manifest.get("feed_source")!="de-national":
        raise RuntimeError("Safety stop: expected de-national feed")
    counts=manifest.get("counts",{})
    if not 500 < int(counts.get("stops",0)) < 100000:
        raise RuntimeError("Safety stop: implausible number of stops")
    if not 500 < int(counts.get("trips",0)) < 500000:
        raise RuntimeError("Safety stop: implausible number of trips")
    if not 5000 < int(counts.get("stop_times",0)) <= MAX_STOP_TIMES:
        raise RuntimeError("Safety stop: too many stop_times for CI benchmark")
    for name,(file,_) in IMPORT_FILES.items():
        if not (args.dir/file).is_file():
            raise RuntimeError("Missing required CSV: "+file)
    if os.environ.get("LDP_TRANSIT_DB_URL"):
        raise RuntimeError("Safety stop: production Supabase DB credential is present in benchmark environment")

    started=time.monotonic()
    with psycopg.connect(args.db_url,autocommit=True,connect_timeout=10) as conn:
        with conn.cursor() as cur:
            cur.execute("select current_database(), current_user, inet_server_addr()")
            db,user,server=cur.fetchone()
            if (db,user)!=(EXPECTED_DB,EXPECTED_USER):
                raise RuntimeError("Safety stop: not connected to intended disposable PostgreSQL")
            cur.execute("select to_regnamespace('legacy_bench'),to_regnamespace('compact_bench')")
            if cur.fetchone()!=(None,None):
                raise RuntimeError("Safety stop: benchmark schemas already exist (use a fresh disposable DB)")

            print("Local PostgreSQL benchmark (no production DB access)",flush=True)
            cur.execute(RAW_DDL)
            for name,(filename,cols) in IMPORT_FILES.items():
                t=time.monotonic()
                copy_csv(cur,name,args.dir/filename,cols)
                print("COPY",name,"seconds",round(time.monotonic()-t,1),flush=True)

            for name in ("stops","trips","stop_times"):
                cur.execute("select count(*) from legacy_bench."+name)
                n=cur.fetchone()[0]
                if n!=int(counts[name]):
                    raise RuntimeError("Raw COPY count mismatch: "+name+" "+str(n)+" != "+str(counts[name]))

            # Mirrors all essential lookup indexes of the existing production schema.
            cur.execute("alter table legacy_bench.stops add primary key(feed_source,stop_id)")
            cur.execute("alter table legacy_bench.trips add primary key(feed_source,trip_id)")
            cur.execute("alter table legacy_bench.stop_times add primary key(feed_source,trip_id,stop_sequence)")
            cur.execute("create index on legacy_bench.stop_times(feed_source,stop_id,departure_secs)")
            cur.execute("analyze legacy_bench.stops")
            cur.execute("analyze legacy_bench.trips")
            cur.execute("analyze legacy_bench.stop_times")

            cur.execute(COMPACT_DDL)
            t=time.monotonic()
            cur.execute("""insert into compact_bench.stops
                (feed_source,stop_id,stop_name,stop_code,parent_station,platform_code,stop_lat,stop_lon)
                select feed_source,stop_id,stop_name,stop_code,parent_station,platform_code,stop_lat,stop_lon
                from legacy_bench.stops order by stop_id""")
            cur.execute("""insert into compact_bench.trips
                (feed_source,trip_id,route_id,service_id,trip_headsign,trip_short_name,direction_id,shape_id)
                select feed_source,trip_id,route_id,service_id,trip_headsign,trip_short_name,direction_id,shape_id
                from legacy_bench.trips order by trip_id""")
            cur.execute("""insert into compact_bench.stop_times
                (trip_key,stop_sequence,stop_key,arrival_secs,departure_secs,stop_headsign,pickup_type,drop_off_type)
                select tm.trip_key,st.stop_sequence,sm.stop_key,st.arrival_secs,st.departure_secs,
                       st.stop_headsign,st.pickup_type::smallint,st.drop_off_type::smallint
                from legacy_bench.stop_times st
                join compact_bench.trips tm on tm.feed_source=st.feed_source and tm.trip_id=st.trip_id
                join compact_bench.stops sm on sm.feed_source=st.feed_source and sm.stop_id=st.stop_id""")
            print("Compact load seconds",round(time.monotonic()-t,1),flush=True)

            cur.execute("alter table compact_bench.stop_times add primary key(trip_key,stop_sequence)")
            cur.execute("create index on compact_bench.stop_times(stop_key,departure_secs)")
            for name in ("stops","trips","stop_times"):
                cur.execute("analyze compact_bench."+name)
                cur.execute("select count(*) from compact_bench."+name)
                count=cur.fetchone()[0]
                if count!=int(counts[name]):
                    raise RuntimeError("Compact count mismatch "+name+" "+str(count))

            # Exhaustive validation: every imported row must still resolve to
            # the same trip, stop, sequence and all GTFS time/boarding fields.
            # This checks the entire dataset, in addition to representative
            # API-shaped departures/trip-route samples below.
            cur.execute("""
                select count(*), count(*) filter (
                    where sm.stop_id is distinct from st.stop_id
                       or ct.arrival_secs is distinct from st.arrival_secs
                       or ct.departure_secs is distinct from st.departure_secs
                       or ct.stop_headsign is distinct from st.stop_headsign
                       or ct.pickup_type::integer is distinct from st.pickup_type
                       or ct.drop_off_type::integer is distinct from st.drop_off_type
                )
                from legacy_bench.stop_times st
                join compact_bench.trips tm on tm.feed_source=st.feed_source
                    and tm.trip_id=st.trip_id
                join compact_bench.stop_times ct on ct.trip_key=tm.trip_key
                    and ct.stop_sequence=st.stop_sequence
                join compact_bench.stops sm on sm.stop_key=ct.stop_key
            """)
            checked_rows, changed_rows=cur.fetchone()
            if checked_rows!=int(counts["stop_times"]) or changed_rows!=0:
                raise RuntimeError("Exhaustive compact GTFS fidelity failed: "+
                                   str(checked_rows)+" matched / "+str(changed_rows)+" changed")

            # Verify information retained: keys, times, all stop sequence,
            # stop-specific headsigns and pickup/drop-off flags on representative trips.
            cur.execute("""select trip_id from legacy_bench.stop_times
                group by trip_id order by count(*) desc,trip_id limit 12""")
            trip_ids=[x[0] for x in cur.fetchall()]
            if len(trip_ids)<10: raise RuntimeError("Not enough routes for correctness check")
            checked_routes=0
            route_times=[]
            for trip_id in trip_ids:
                a,ms_a=timed(cur,RAW_ROUTE,(trip_id,),3)
                b,ms_b=timed(cur,COMPACT_ROUTE,(trip_id,),3)
                if a!=b: raise RuntimeError("Trip route mismatch for "+trip_id)
                checked_routes+=1
                route_times.append((ms_a,ms_b))

            cur.execute("""select stop_id from legacy_bench.stop_times
                group by stop_id order by count(*) desc,stop_id limit 6""")
            stop_ids=[x[0] for x in cur.fetchall()]
            if len(stop_ids)<4: raise RuntimeError("Not enough stops for correctness check")
            checks=[]
            for sid in stop_ids:
                for lower,upper in ((0,43200),(43201,86400),(86401,120000)):
                    a,ms_a=timed(cur,RAW_DEPS,(sid,lower,upper))
                    b,ms_b=timed(cur,COMPACT_DEPS,(sid,lower,upper))
                    if a!=b:
                        raise RuntimeError("Departure mismatch for stop "+sid+" seconds "+str(lower))
                    checks.append({"stop":sid,"window":[lower,upper],"count":len(a),
                                   "legacy_ms":ms_a,"compact_ms":ms_b})

            legacy=size_breakdown(cur,"legacy_bench")
            compact=size_breakdown(cur,"compact_bench")
            saved=round(100*(1-compact["total_mb"]/legacy["total_mb"]),2)
            if saved < 5:
                raise RuntimeError("Compact storage does not save at least 5%: "+str(saved))
            result={
                "ok":True,"scope":"disposable local PostgreSQL only","source":"Germany 4-city core",
                "input_counts":{x:int(counts[x]) for x in ("stops","trips","stop_times")},
                "legacy":legacy,"compact":compact,"size_reduction_pct":saved,
                "tested_trip_routes":checked_routes,
                "tested_departure_windows":len(checks),
                "departure_samples":checks,
                "trip_route_median_ms":{
                    "legacy":round(statistics.median(t[0] for t in route_times),2),
                    "compact":round(statistics.median(t[1] for t in route_times),2)},
                "runtime_seconds":round(time.monotonic()-started,2),
                "deployment_decision":"NOT APPROVED; production backup, quota and compatibility gates still required"
            }
            print("BENCHMARK_PASS",json.dumps(result,indent=2),flush=True)
            if args.report:
                args.report.write_text(json.dumps(result,indent=2)+"\n",encoding="utf-8")
    return 0

if __name__=="__main__":
    raise SystemExit(main())
