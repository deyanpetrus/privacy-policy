#!/usr/bin/env python3
"""
LifeDashPro v37.83 — feed-safe PostgreSQL GTFS subset importer.

Imports a selective GTFS subset (generated by germany_gtfs_selective_extract.py)
directly into the LifeDashPro Supabase Postgres database using COPY.

Safety:
- Requires explicit --confirm-feed-source matching manifest feed_source.
- Runs in one transaction.
- Replaces only one feed_source.
- Does not touch any non-transit tables.
- On any failure, transaction rolls back.
- DB URL is read from LDP_TRANSIT_DB_URL environment variable by default.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from datetime import date, timedelta

try:
    import psycopg
    from psycopg.types.json import Jsonb
except Exception:
    print(
        "Missing dependency: psycopg. Install with:\n"
        "  python -m pip install \"psycopg[binary]\"\n",
        file=sys.stderr,
    )
    raise

TABLES = [
    ("transit_gtfs_stops","stops.csv",
     ["feed_source","stop_id","stop_name","stop_code","parent_station","platform_code","stop_lat","stop_lon"]),
    ("transit_gtfs_routes","routes.csv",
     ["feed_source","route_id","agency_id","route_short_name","route_long_name","route_type","route_color","route_text_color"]),
    ("transit_gtfs_trips","trips.csv",
     ["feed_source","trip_id","route_id","service_id","trip_headsign","trip_short_name","direction_id","shape_id"]),
    ("transit_gtfs_calendar","calendar.csv",
     ["feed_source","service_id","monday","tuesday","wednesday","thursday","friday","saturday","sunday","start_date","end_date"]),
    ("transit_gtfs_calendar_dates","calendar_dates.csv",
     ["feed_source","service_id","service_date","exception_type"]),
    ("transit_gtfs_shapes","shapes.csv",
     ["feed_source","shape_id","shape_pt_sequence","shape_pt_lat","shape_pt_lon","shape_dist_traveled"]),
    ("transit_gtfs_stop_times","stop_times.csv",
     ["feed_source","trip_id","stop_sequence","stop_id","arrival_time","departure_time","arrival_secs","departure_secs","stop_headsign","pickup_type","drop_off_type"]),
]

def copy_csv(cur, table: str, csv_path: Path, columns: list[str], batch_rows: int | None = None) -> None:
    cols = ", ".join(columns)
    size_mb = csv_path.stat().st_size / (1024 * 1024)

    if not batch_rows:
        sql = f'COPY public.{table} ({cols}) FROM STDIN WITH (FORMAT CSV, HEADER TRUE)'
        print(f"  COPY {csv_path.name} -> {table} ({size_mb:.1f} MB)", flush=True)
        with cur.copy(sql) as cp:
            with csv_path.open("rb") as f:
                while True:
                    chunk = f.read(1024 * 1024)
                    if not chunk:
                        break
                    cp.write(chunk)
        return

    print(
        f"  COPY {csv_path.name} -> {table} ({size_mb:.1f} MB) "
        f"in batches of {batch_rows:,} rows",
        flush=True,
    )
    sql = f'COPY public.{table} ({cols}) FROM STDIN WITH (FORMAT CSV, HEADER TRUE)'
    with csv_path.open("rb") as f:
        header = f.readline()
        if not header:
            return

        batch_no = 0
        total_rows = 0
        while True:
            lines = []
            for _ in range(batch_rows):
                line = f.readline()
                if not line:
                    break
                lines.append(line)

            if not lines:
                break

            batch_no += 1
            with cur.copy(sql) as cp:
                cp.write(header)
                for line in lines:
                    cp.write(line)

            total_rows += len(lines)
            print(
                f"    batch {batch_no}: {len(lines):,} rows "
                f"(total {total_rows:,})",
                flush=True,
            )

            if len(lines) < batch_rows:
                break

def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True, help="Subset directory containing manifest.json and CSVs")
    ap.add_argument("--db-url-env", default="LDP_TRANSIT_DB_URL")
    ap.add_argument("--confirm-feed-source", required=True)
    ap.add_argument("--priority", type=int, default=50)
    ap.add_argument("--region", default="Germany")
    ap.add_argument("--source-url", default="https://download.gtfs.de/germany/nv_free/latest.zip")
    ap.add_argument("--check-only", action="store_true", help="Verify connection/schema only; write nothing")
    args = ap.parse_args()

    root = Path(args.dir)
    manifest_path = root / "manifest.json"
    if not manifest_path.exists():
        raise SystemExit(f"manifest.json not found: {manifest_path}")

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    feed_source = str(manifest.get("feed_source") or "").strip()
    if not feed_source:
        raise SystemExit("Manifest has no feed_source")
    if feed_source != args.confirm_feed_source:
        raise SystemExit(
            f"Safety stop: manifest feed_source={feed_source!r} does not match "
            f"--confirm-feed-source={args.confirm_feed_source!r}"
        )

    for _, filename, _ in TABLES:
        p = root / filename
        if not p.exists():
            raise SystemExit(f"Required file missing: {p}")

    db_url = (os.environ.get(args.db_url_env) or "").strip()
    if not db_url:
        raise SystemExit(
            f"Environment variable {args.db_url_env} is not set.\n"
            "Set it locally to your Supabase Session pooler/Postgres connection string.\n"
            "Do not paste the database password into chat."
        )

    counts = manifest.get("counts") or {}
    print("LifeDashPro v37.83 GTFS subset import")
    print(f"  feed_source: {feed_source}")
    print(f"  subset:      {root}")
    print(f"  stops:       {counts.get('stops', '?')}")
    print(f"  routes:      {counts.get('routes', '?')}")
    print(f"  trips:       {counts.get('trips', '?')}")
    print(f"  stop_times:  {counts.get('stop_times', '?')}")
    print("  mode:        transactional feed-scoped replace")
    print()

    # Advertise only the refresh window covered by the validated imported subset.
    window_start = date.fromisoformat(manifest["selection"]["service_date"])
    window_days = int(manifest["selection"]["service_days"])
    if window_days < 14 or window_days > 31:
        raise SystemExit("Safety stop: scheduled import needs a 14–31 day GTFS window")
    window_end = window_start + timedelta(days=window_days - 1)

    metadata = {
        "lifedash_version": "37.83.0",
        "selection": manifest.get("selection", {}),
        "geometry": manifest.get("geometry", {}),
        "counts": counts,
        "source_zip_bytes": manifest.get("source_zip_bytes"),
    }

    with psycopg.connect(db_url, autocommit=False) as conn:
        try:
            with conn.cursor() as cur:
                print("[1/4] Verifying transit schema ...", flush=True)
                cur.execute(
                    """
                    select to_regclass('public.transit_gtfs_feeds'),
                           to_regclass('public.transit_gtfs_stop_times')
                    """
                )
                a, b = cur.fetchone()
                if not a or not b:
                    raise RuntimeError("v37.83 transit schema is missing on remote database")
                if args.check_only:
                    conn.rollback()
                    print("CHECK OK — connection works and v37.83 transit schema exists. No data written.", flush=True)
                    return 0

                print("[2/4] Replacing only feed_source =", feed_source, flush=True)
                cur.execute("delete from public.transit_gtfs_feeds where feed_source = %s", (feed_source,))
                cur.execute(
                    """
                    insert into public.transit_gtfs_feeds
                      (feed_source, name, region, timezone, priority, active,
                       source_url, imported_at, feed_start_date, feed_end_date, metadata)
                    values
                      (%s, %s, %s, 'Europe/Berlin', %s, true,
                       %s, now(), %s, %s, %s)
                    """,
                    (
                        feed_source,
                        manifest.get("feed_name") or feed_source,
                        args.region,
                        args.priority,
                        args.source_url,
                        (manifest.get("selection") or {}).get("service_date"),
                        window_end.isoformat(),
                        Jsonb(metadata),
                    ),
                )

                print("[3/4] COPY subset CSVs ...", flush=True)

                # Session-pooler connections can inherit a relatively short
                # statement_timeout. Keep this transaction atomic, but avoid one
                # very long COPY statement for the largest table.
                cur.execute("set local statement_timeout = '10min'")
                cur.execute("set local lock_timeout = '30s'")

                for table, filename, columns in TABLES:
                    if table == "transit_gtfs_stop_times":
                        copy_csv(cur, table, root / filename, columns, batch_rows=100_000)
                    else:
                        copy_csv(cur, table, root / filename, columns)

                print("[4/4] Verifying row counts ...", flush=True)
                checks = {}
                for table, _, _ in TABLES:
                    cur.execute(
                        f"select count(*) from public.{table} where feed_source = %s",
                        (feed_source,),
                    )
                    checks[table] = cur.fetchone()[0]

                expected_map = {
                    "transit_gtfs_stops": counts.get("stops"),
                    "transit_gtfs_routes": counts.get("routes"),
                    "transit_gtfs_trips": counts.get("trips"),
                    "transit_gtfs_stop_times": counts.get("stop_times"),
                    "transit_gtfs_calendar": counts.get("calendar"),
                    "transit_gtfs_calendar_dates": counts.get("calendar_dates"),
                    "transit_gtfs_shapes": counts.get("shape_points"),
                }
                mismatches = []
                for table, expected in expected_map.items():
                    if expected is not None and int(expected) != int(checks.get(table, -1)):
                        mismatches.append((table, expected, checks.get(table)))
                if mismatches:
                    raise RuntimeError(f"Row-count verification failed: {mismatches}")

                print(json.dumps({
                    "ok": True,
                    "feed_source": feed_source,
                    "rows": checks,
                    "geometry": manifest.get("geometry"),
                }, indent=2, ensure_ascii=False))

            conn.commit()
            print("COMMIT OK — feed import completed.", flush=True)
            return 0
        except Exception:
            conn.rollback()
            print("ROLLBACK — no partial feed import was kept.", file=sys.stderr, flush=True)
            raise

if __name__ == "__main__":
    raise SystemExit(main())