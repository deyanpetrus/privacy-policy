/* LifeDashPro Desktop v1.27 — canonical read-only Today/Next 10 day aggregator.
 * Uses actual synchronized Android/Web rows; never modifies source records.
 */
(()=>{
'use strict';
const pad=n=>String(n).padStart(2,'0');
const ymd=d=>d.getFullYear()+'-'+pad(d.getMonth()+1)+'-'+pad(d.getDate());
function parseDate(value){
 const m=String(value??'').trim().match(/^(\d{4})[-/](\d{1,2})[-/](\d{1,2})(?:$|T|\s)/)||
  String(value??'').trim().match(/^(\d{1,2})[./](\d{1,2})[./](\d{4})$/);
 if(!m)return '';
 const western=String(m[1]).length===4;
 const y=+(western?m[1]:m[3]),mo=+(m[2]),day=+(western?m[3]:m[1]);
 const d=new Date(y,mo-1,day,12);
 return d.getFullYear()===y&&d.getMonth()+1===mo&&d.getDate()===day?ymd(d):'';
}
const blocked=r=>r?.deleted===true||r?.isDeleted===true||r?.archived===true||
 ['archived','completed','done','cancelled','canceled','deleted'].includes(String(r?.status||'').toLowerCase())||
 r?.done===true||r?.completed===true||r?.isCompleted===true;
function collect(calendar,finance,now=new Date()){
 const today=new Date(now.getFullYear(),now.getMonth(),now.getDate(),12);
 const last=new Date(today);last.setDate(last.getDate()+10);
 const from=ymd(today),to=ymd(last);
 const records=[],seen=new Set(),input=calendar||{};
 const add=(kind,r,raw,title,opts={})=>{
  const date=parseDate(raw),name=String(title||opts.fallback||'').trim();
  if(!date||!name)return;
  const key=kind+'|'+String(r?.id||name)+'|'+date;
  if(seen.has(key))return;seen.add(key);
  records.push({kind,id:String(r?.id||''),date,title:name.slice(0,100),
   time:String(opts.time||'').slice(0,5),page:opts.page||'today'});
 };
 for(const r of input.notes||[]){
  if(blocked(r))continue;
  add('notes',r,r.dueDate,r.title,{fallback:'Note',page:'notes',time:r.dueTime});
 }
 for(const r of input.family_tasks||[]){
  if(blocked(r))continue;
  add('tasks',r,r.dueDate||r.scheduledFor,r.title,
   {fallback:'Task',page:'tasks',time:r.reminderTime});
 }
 for(const r of input.manual_reminders||[]){
  if(blocked(r))continue;
  add('reminders',r,r.dueDate||r.date||r.scheduledFor,r.title||r.text,
   {fallback:'Reminder',page:'today',time:r.time||r.reminderTime});
 }
 for(const r of input.documents||[]){
  if(r.deleted===true||r.isDeleted===true||r.archived===true)continue;
  add('documents',r,r.expiresAt||r.expiryDate,r.name||r.title,
   {fallback:'Document',page:'documents'});
 }
 for(const r of input.family_members||[]){
  if(r.deleted||r.isDeleted)continue;
  const born=parseDate(r.birthday||r.birthDate);
  if(!born)continue;
  const [by,bm,bd]=born.split('-').map(Number);
  for(let y=today.getFullYear()-1;y<=today.getFullYear()+1;y++){
   const date=new Date(y,bm-1,bd,12);
   if(date.getMonth()!==bm-1)continue; // Feb 29 not guessed in other years.
   add('birthdays',r,ymd(date),r.name||r.firstName,
    {fallback:'Birthday',page:'calendar'});
  }
 }
 // Only posted *actual* transactions dated today, not copies generated by
 // monthly recurrence. Recurrence remains exclusively in the Finance calculator.
 for(const r of finance||[]){
  if(r.isPaid!==true||!['income','expense'].includes(r.type)||blocked(r))continue;
  const date=parseDate(r.date);
  if(date!==from)continue;
  const amount=Number(r.amount);
  const title=String(r.description||r.title||r.category||'Transaction');
  let display=title;
  if(Number.isFinite(amount)&&amount>=0&&/^[A-Z]{3}$/.test(String(r.currency||'EUR')))
   display+=' · '+(r.type==='expense'?'−':'+')+amount.toFixed(2)+' '+String(r.currency||'EUR');
  add('finance',r,date,display,{page:'finance'});
 }
 const sort=(a,b)=>a.date.localeCompare(b.date)||
  a.time.localeCompare(b.time)||a.title.localeCompare(b.title);
 const todayItems=records.filter(r=>r.date===from).sort(sort);
 const next=records.filter(r=>r.date>from&&r.date<=to).sort(sort);
 const overdue=records.filter(r=>r.date<from&&r.kind!=='finance'&&r.kind!=='birthdays').sort(sort);
 return {today:todayItems,next,overdue,from,to,total:records.length};
}
window.LifeDashTodayV127=Object.freeze({collect,parseDate,ymd});
})();
